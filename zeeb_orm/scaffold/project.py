def zeeb_version() -> str:
    """Installed zeebpy version, or ``"unknown"`` from a source checkout."""
    from importlib.metadata import PackageNotFoundError, version

    try:
        return version("zeebpy")
    except PackageNotFoundError:
        return "unknown"


