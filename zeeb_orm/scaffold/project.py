def generate_secret_key() -> str:
    """Return a fresh per-project signing key for the generated ``.env``.

    ``token_urlsafe`` yields only ``[A-Za-z0-9_-]``, so the value needs no
    quoting in a ``.env`` file and can never contain ``#``, ``=`` or a newline.
    64 bytes is well above the 32 that HS256 wants, and the result is by
    construction not one of ``zeeb_api.auth.jwt.INSECURE_SECRETS`` — which is
    what lets a generated project run with ``DEBUG=false`` out of the box.
    """
    return secrets.token_urlsafe(64)


