def test_the_urls_template_imports_no_app():
    """It is written into arbitrary projects, so it cannot assume an app."""
    assert "apps." not in wiring.STANDARD_URLS_TEMPLATE


def test_the_urls_template_stays_wireable():
    """`append_router_include` refuses a urls.py it cannot edit safely."""
    tree = ast.parse(wiring.STANDARD_URLS_TEMPLATE)
    assigned = {
        target.id
        for node in tree.body
        if isinstance(node, ast.Assign)
        for target in node.targets
        if isinstance(target, ast.Name)
    }
    assert "router" in assigned
    assert any(
        isinstance(node, ast.FunctionDef) and node.name == "get_routes" for node in tree.body
    )


def test_the_auth_include_appears_exactly_once():
    """setup_auth counts this exact prefix to detect a duplicate include."""
    assert wiring.STANDARD_URLS_TEMPLATE.count("router.include(create_auth_router(") == 1


def test_generated_secret_keys_are_strong_and_unique():
    from zeeb_api.auth.jwt import INSECURE_SECRETS

    keys = {project_templates.generate_secret_key() for _ in range(20)}
    assert len(keys) == 20
    for key in keys:
        assert key not in INSECURE_SECRETS
        assert len(key) >= 43
        # No quoting needed in a .env file.
        assert not set(key) & set("#= \n\"'")


# ---------------------------------------------------------------------------
# Drift guard: the scaffold may only set settings the framework reads
# ---------------------------------------------------------------------------

# Names the template defines for its own use rather than as framework settings.
TEMPLATE_LOCALS = {
    "BASE_DIR",
    "DEFAULT_DATABASE_URL",
    "_ANON_THROTTLE",
    "_USER_THROTTLE",
    "_HEADER_VERSIONING",
    "AUTH_URL_PREFIX",
    "AUTH_ENABLE_REGISTRATION",
    "AUTH_LOGIN_THROTTLE_RATE",
}


def scaffolded_setting_names() -> set[str]:
    source = project_templates.SETTINGS_PY.format(project_name="demo_api")
    return {
        target.id
        for node in ast.parse(source).body
        if isinstance(node, ast.Assign)
        for target in node.targets
        if isinstance(target, ast.Name) and target.id.isupper()
    }


def test_every_scaffolded_setting_is_a_real_one():
    """A typo'd setting name is silently ignored at runtime — catch it here."""
    from zeeb_api.conf import default_settings

    known = {name for name in dir(default_settings) if name.isupper()}
    unknown = scaffolded_setting_names() - known - TEMPLATE_LOCALS
    assert not unknown, f"settings.py sets names the framework never reads: {sorted(unknown)}"


def test_the_scaffold_turns_the_batteries_on():
    """The point of the boilerplate: these are configured, not left to chance."""
    source = project_templates.SETTINGS_PY.format(project_name="demo_api")
    for expected in (
        'AUTH_USER_MODEL = "accounts.User"',
        'ROOT_URLCONF = "demo_api.urls"',
        "zeeb_api.middleware.CORSMiddleware",
        "zeeb_api.versioning.VersioningMiddleware",
        "zeeb_api.middleware.JWTAuthMiddleware",
        "DEFAULT_THROTTLE_CLASSES",
        "DEFAULT_VERSIONING_CLASS",
        "OAUTH_PROVIDERS = env_oauth_providers()",
        "INSTALL_HEALTH_ROUTES = True",
    ):
        assert expected in source, expected


def test_the_rendered_settings_defaults(tmp_path):
    """Execute the template the way a project would and check the defaults."""
    from zeeb_api.conf.env import clear_env_cache

    clear_env_cache()
    settings_file = tmp_path / "demo_api" / "settings.py"
    settings_file.parent.mkdir()
    settings_file.write_text(project_templates.SETTINGS_PY.format(project_name="demo_api"))

    namespace: dict = {"__file__": str(settings_file)}
    exec(compile(settings_file.read_text(), str(settings_file), "exec"), namespace)

    # A non-empty origin list matters: install_middleware skips CORSMiddleware
    # entirely when it is empty, and describe_project reports that as a warning.
    assert namespace["CORS_ALLOW_ORIGINS"]
    assert namespace["DEBUG"] is True
    assert namespace["AUTH_USER_MODEL"] == "accounts.User"
    assert namespace["INSTALLED_APPS"] == ["apps.accounts"]
    assert namespace["OAUTH_PROVIDERS"] == {}
    assert namespace["ALLOWED_VERSIONS"] == ["1.0"]
    assert namespace["DEFAULT_THROTTLE_RATES"] == {"anon": "120/min", "user": "1200/min"}
    # Paths are anchored at the project root, not the working directory.
    assert str(tmp_path) in namespace["DATABASE"]["url"]


def test_provider_names_stay_out_of_the_settings_template():
    """`setup_oauth` treats a provider literal here as "already configured"."""
    source = project_templates.SETTINGS_PY.format(project_name="demo_api")
    oauth_section = source[source.index("OAUTH_PROVIDERS"):]
    for provider in ('"google"', '"github"', '"azure"'):
        assert provider not in oauth_section, provider


def test_the_settings_template_stays_single_line_assignable():
    """`manage_settings` can only rewrite a setting that fits on one line."""
    source = project_templates.SETTINGS_PY.format(project_name="demo_api")
    # Collection-valued settings are exempt: manage_settings only writes
    # scalars, so it would never target them anyway.
    multiline_ok = {
        "DATABASE",
        "INSTALLED_APPS",
        "MIDDLEWARE",
        "LOGGING",
        "DEFAULT_THROTTLE_RATES",
        "DEFAULT_THROTTLE_CLASSES",
        "CORS_ALLOW_ORIGINS",
    }
    for node in ast.parse(source).body:
        if not isinstance(node, ast.Assign):
            continue
        target = node.targets[0]
        if not isinstance(target, ast.Name) or not target.id.isupper():
            continue
        if target.id in multiline_ok:
            continue
        assert node.lineno == node.end_lineno, f"{target.id} spans multiple lines"
