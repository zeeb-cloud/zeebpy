"""Guards on the scaffolding templates themselves.

The templates are rendered with ``str.format``, so an unescaped brace or a
typo'd setting name only surfaces when someone actually scaffolds a project.
These checks catch both at test time.
"""

import ast
import re

import pytest

from zeeb_agents import test_scaffold
from zeeb_orm.scaffold import accounts, harness, wiring
from zeeb_orm.scaffold import app as app_templates
from zeeb_orm.scaffold import project as project_templates

PROJECT_MODULES = {
    "MANAGE_PY": {},
    "SETTINGS_PY": {"project_name": "demo_api"},
    "URLS_PY": {},
    "ASGI_PY": {"project_name": "demo_api"},
    "PROJECT_INIT_PY": {"project_name": "demo_api"},
    "APPS_INIT_PY": {},
}

APP_CONTEXT = {
    "app_name": "shop",
    "app_class": "Shop",
    "app_title": "Shop",
    "model_name": "Shop",
    "model_slug": "shop",
    "table_name": "shop_shop",
    "route_prefix": "shops",
}


def render(template: str, context: dict) -> str:
    return template.format(**context) if context else template


@pytest.mark.parametrize("name,context", PROJECT_MODULES.items())
def test_project_templates_compile(name, context):
    source = render(getattr(project_templates, name), context)
    compile(source, f"{name}.py", "exec")


@pytest.mark.parametrize(
    "name",
    [
        "MODELS_PY",
        "SERIALIZERS_PY",
        "VIEWS_PY",
        "URLS_PY",
        "APP_INIT_PY",
        "TESTS_PY",
        "SLICE_MODELS_PY",
        "SLICE_SERIALIZERS_PY",
        "SLICE_VIEWS_PY",
        "SLICE_URLS_PY",
        "SLICE_TESTS_PY",
    ],
)
def test_app_templates_compile(name):
    compile(getattr(app_templates, name).format(**APP_CONTEXT), f"{name}.py", "exec")


@pytest.mark.parametrize(
    "name", ["MODELS_PY", "SERIALIZERS_PY", "VIEWS_PY", "URLS_PY", "TESTS_PY"]
)
def test_the_default_app_templates_teach_through_their_docstring(name):
    """The canonical example lives in the docstring, not in commented-out code.

    A comment neither lints nor runs, and an agent that copies one gets a
    comment. The docstring survives every edit to the file below it.
    """
    module = ast.parse(getattr(app_templates, name).format(**APP_CONTEXT))
    docstring = ast.get_docstring(module)
    assert docstring, f"{name} has no module docstring"
    if name != "TESTS_PY":
        assert APP_CONTEXT["model_name"] in docstring, f"{name} shows no example"


